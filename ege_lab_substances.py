def category_counts():
    result = {}
    for value in REAGENTS.values():
        result[value[1]] = result.get(value[1], 0) + 1
    return result


def validate_catalog():
    if len(REAGENTS) != len(set(REAGENTS)):
        raise RuntimeError("duplicate reagent ids")
    for key, value in REAGENTS.items():
        if len(value) < 3 or not value[0] or not value[1]:
            raise RuntimeError(f"invalid reagent: {key}")
    return True


validate_catalog()
