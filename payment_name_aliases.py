def stable_name_key(value):
    cleaned = payments._clean_name(value).casefold()
    return ALIASES.get(cleaned, cleaned)


payments._name_key = stable_name_key


def refresh_existing_labels():
    payments.ensure_payment_tables()
    now = payments.datetime.now(bot.TIMEZONE).isoformat()
    with sqlite3.connect(bot.COREAPP_DB_PATH) as conn:
        for source_key, display_name in DISPLAY.items():
            conn.execute(
                "UPDATE payment_students SET display_name = ?, updated_at = ? WHERE source_key = ? AND source_sheet = ?",
                (display_name, now, source_key, payments.PAYMENT_SHEET_NAME),
            )
        conn.commit()


refresh_existing_labels()
